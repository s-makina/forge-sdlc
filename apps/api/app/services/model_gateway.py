"""LiteLLM gateway integration.

The DB is the source of truth for providers and models. This module

- renders a LiteLLM ``config.yaml`` document from the configured providers, so
  the gateway can be deployed from the platform rather than hand-edited; and
- talks to a running LiteLLM proxy's health endpoints for on-demand checks.

The read-only API config omits decrypted credentials. The local config apply action
embeds decrypted keys because LiteLLM must receive the configured provider secret.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from app.core.config import get_settings
from app.core.secrets import CredentialError, decrypt_credential
from app.models.capabilities import ModelCapability
from app.models.model_provider import ModelProvider, ProviderType

_LITELLM_PROVIDER_PREFIX = {
    ProviderType.OLLAMA: "ollama_chat",
    ProviderType.OPENAI_COMPATIBLE: "openai",
}

_CAPABILITY_FLAGS = {
    ModelCapability.TOOL_CALLING: "supports_function_calling",
    ModelCapability.STRUCTURED_OUTPUT: "supports_response_schema",
    ModelCapability.VISION: "supports_vision",
}


def _env_name(credential_ref: str | None) -> str | None:
    if credential_ref is None:
        return None
    scheme, _, name = credential_ref.partition(":")
    if scheme != "env" or not name:
        raise CredentialError("Only 'env:NAME' credential references can render LiteLLM config")
    return name


def render_litellm_config(
    providers: list[ModelProvider], *, include_raw_credentials: bool = False
) -> dict[str, Any]:
    """Render a LiteLLM proxy config, optionally embedding decrypted local credentials."""
    model_list: list[dict[str, Any]] = []
    for provider in providers:
        if not provider.is_active:
            continue
        try:
            prefix = _LITELLM_PROVIDER_PREFIX[ProviderType(provider.provider_type)]
        except ValueError:
            continue
        env_name = (
            _env_name(provider.credential_ref)
            if provider.credential_ref and not provider.credential_ciphertext
            else None
        )
        raw_key = None
        if include_raw_credentials and provider.credential_ciphertext:
            raw_key = decrypt_credential(
                provider.credential_ciphertext, get_settings().credential_encryption_key
            )
        for model in provider.models:
            if not model.is_active:
                continue
            params: dict[str, Any] = {
                "model": f"{prefix}/{model.name}",
                "api_base": provider.base_url,
            }
            if raw_key:
                params["api_key"] = raw_key
            elif env_name:
                params["api_key"] = f"os.environ/{env_name}"
            elif provider.credential_ciphertext:
                params["api_key"] = "<configured>"
            info: dict[str, Any] = {}
            for capability, flag in _CAPABILITY_FLAGS.items():
                if capability.value in model.capabilities:
                    info[flag] = True
            model_list.append(
                {
                    "model_name": model.name,
                    "litellm_params": params,
                    "model_info": info,
                }
            )

    return {
        "model_list": model_list,
        "litellm_settings": {"drop_params": True},
    }


def _yaml_document(config: dict[str, Any]) -> str:
    header = (
        "# Generated by ForgeSDLC from the model provider registry.\n"
        "# Do not edit by hand; configure providers through the platform API.\n"
        f"# Generated at: {datetime.now(UTC).isoformat()}\n"
    )
    return header + yaml.safe_dump(config, sort_keys=False)


def render_litellm_yaml(providers: list[ModelProvider]) -> str:
    return _yaml_document(render_litellm_config(providers))


def write_litellm_config(providers: list[ModelProvider], path: str) -> int:
    """Render the gateway config and write it to ``path``.

    The target file is overwritten in place rather than replaced so a
    bind-mounted ``config.yaml`` keeps its inode. LiteLLM reads the file at
    startup, so it must be reloaded or restarted to pick up the new content.

    Returns the number of models written to the config.
    """
    config = render_litellm_config(providers, include_raw_credentials=True)
    target = Path(path).expanduser()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(_yaml_document(config), encoding="utf-8")
    try:
        target.chmod(0o600)
    except (OSError, NotImplementedError):
        # Windows ACLs do not map to POSIX mode bits; the containing project
        # directory must be protected by the operator on that platform.
        pass
    return len(config["model_list"])
